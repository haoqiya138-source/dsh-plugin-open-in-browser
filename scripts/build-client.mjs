#!/usr/bin/env node
/**
 * Build the browser half.
 *
 * DSH loads a UI plugin's `./client` export as a bare module body wrapped in
 * `window.__ModuleLoader__.load({ id, factory(require) { ... } })`: the factory may
 * only `require` modules the browser module table publishes (here: `react`), and
 * it must `return` the plugin's `inject` list plus its `apply(ctx)` function.
 *
 * There is no bundler in this project, so the build compiles `src/client.ts` and
 * `src/security.ts` with `tsc`, concatenates the two emitted modules in dependency
 * order, strips their module syntax, and wraps the result. If a real runtime
 * import survives the strip, the build fails instead of shipping a broken artifact.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tsc = resolve(root, 'node_modules', 'typescript', 'bin', 'tsc')
const buildDir = resolve(root, '.build')
const outFile = resolve(root, 'dist', 'client.js')
const packageJson = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))

if (!existsSync(tsc)) {
  console.error('[build:client] typescript is not installed. Run `npm install` first.')
  process.exit(1)
}

rmSync(buildDir, { recursive: true, force: true })
mkdirSync(buildDir, { recursive: true })
mkdirSync(resolve(root, 'dist'), { recursive: true })

const compiled = spawnSync(process.execPath, [tsc, '-p', resolve(root, 'tsconfig.client.json')], {
  cwd: root,
  stdio: 'inherit',
})
if (compiled.status !== 0) {
  process.exit(compiled.status ?? 1)
}

/** Remove ESM syntax from a compiled module body. */
function stripModuleSyntax(code, label) {
  const stripped = code
    .replace(/^import\s[^\n]*\n/gm, '')
    .replace(/^export\s+(?=(?:default\s+)?(?:async\s+)?(?:declare\s+)?(?:class|function|const|let|var)\s)/gm, '')
    .replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm, '')
    .trim()

  const leftover = /^\s*(?:import|export)\b/m.exec(stripped)
  if (leftover !== null) {
    console.error(`[build:client] ${label} still contains module syntax: ${leftover[0].trim()}`)
    process.exit(1)
  }
  return stripped
}

const securityBody = stripModuleSyntax(readFileSync(resolve(buildDir, 'security.js'), 'utf8'), 'security.js')
const clientBody = stripModuleSyntax(readFileSync(resolve(buildDir, 'client.js'), 'utf8'), 'client.js')

const banner = [
  `/* ${packageJson.name} ${packageJson.version} — generated by scripts/build-client.mjs. Do not edit. */`,
  `window.__ModuleLoader__.load({`,
  `  id: ${JSON.stringify(packageJson.name)},`,
  `  factory(require) {`,
  `    const React = require('react')`,
  ``,
  `    // ---- src/security.ts ----`,
]
const separator = [`    // ---- src/client.ts ----`]
const footer = [
  ``,
  `    return { inject, apply }`,
  `  },`,
  `})`,
  ``,
]

const body = [...banner, securityBody, ...separator, clientBody, ...footer].join('\n')
writeFileSync(outFile, body, 'utf8')

const check = spawnSync(process.execPath, ['--check', outFile], { cwd: root, stdio: 'inherit' })
if (check.status !== 0) {
  console.error('[build:client] dist/client.js failed a syntax check.')
  process.exit(check.status ?? 1)
}

rmSync(buildDir, { recursive: true, force: true })
console.log(`[build:client] dist/client.js ready (${body.length} bytes)`)
